import * as Phaser from "phaser";
import { PLAYER_COLORS } from "../../../../shared/constants";
import { drawCharacterSheet, drawShadow, CHAR_W, CHAR_H, CHAR_FRAMES } from "./characters";
import { drawTileset } from "./tiles";
import {
  drawTree, drawCorn, drawHay, drawPumpkin, drawLantern, drawFence, drawLeaf,
  PROP_ART, TREE_VARIANTS, LEAF_COLORS,
} from "./props";
import type { PropType } from "../../../../shared/map/legend";

/**
 * ART REGISTRY
 * ------------
 * Every texture the game uses is listed here with a function that draws it.
 *
 * How swapping in a real asset pack works:
 *   1. Put a PNG in client/public/assets/
 *   2. Add it to client/public/assets/manifest.json under the same key, e.g.
 *        { "textures": { "tree_0": { "file": "my-tree.png" } } }
 *      For sprite sheets also give "frameWidth" and "frameHeight".
 *   3. Reload. Any key found in the manifest is loaded from the file; anything
 *      not listed is generated by the code below. No game code changes needed,
 *      as long as the new image keeps the same size/frame layout.
 */
export interface ArtEntry {
  key: string;
  draw: () => HTMLCanvasElement;
  /** If set, the texture is a horizontal strip of frames this size. */
  frame?: { w: number; h: number; count: number };
}

export const playerTextureKey = (color: number) => `player_${color}`;
export const propTextureKey = (type: PropType) => `prop_${type}`;

export const ART: ArtEntry[] = [
  { key: "tileset", draw: drawTileset },
  { key: "shadow", draw: drawShadow },
  ...PLAYER_COLORS.map((_, i) => ({
    key: playerTextureKey(i),
    draw: () => drawCharacterSheet(i),
    frame: { w: CHAR_W, h: CHAR_H, count: CHAR_FRAMES },
  })),
  ...Array.from({ length: TREE_VARIANTS }, (_, i) => ({ key: `tree_${i}`, draw: () => drawTree(i) })),
  { key: "corn_0", draw: () => drawCorn(0) },
  { key: "corn_1", draw: () => drawCorn(1) },
  { key: "hay", draw: drawHay },
  { key: "pumpkin", draw: drawPumpkin },
  { key: "lantern", draw: () => drawLantern(false) },
  { key: "lantern_lit", draw: () => drawLantern(true) },
  { key: "fenceH", draw: () => drawFence("fenceH") },
  { key: "fenceV", draw: () => drawFence("fenceV") },
  { key: "fencePost", draw: () => drawFence("fencePost") },
  ...LEAF_COLORS.map((_, i) => ({ key: `leaf_${i}`, draw: () => drawLeaf(i) })),
  ...(Object.keys(PROP_ART) as PropType[]).map((type) => ({ key: propTextureKey(type), draw: PROP_ART[type].draw })),
];

interface ManifestEntry { file: string; frameWidth?: number; frameHeight?: number }

/**
 * Called from the Preloader once manifest.json has loaded: queues every
 * override image so Phaser loads it from disk.
 */
export function queueManifestOverrides(scene: Phaser.Scene) {
  const manifest = scene.cache.json.get("manifest") as { textures?: Record<string, ManifestEntry> } | undefined;
  for (const [key, entry] of Object.entries(manifest?.textures ?? {})) {
    if (entry.frameWidth && entry.frameHeight) {
      scene.load.spritesheet(key, `assets/${entry.file}`, { frameWidth: entry.frameWidth, frameHeight: entry.frameHeight });
    } else {
      scene.load.image(key, `assets/${entry.file}`);
    }
  }
}

/** Draws every registered texture that wasn't loaded from a file. */
export function generateMissingTextures(scene: Phaser.Scene) {
  for (const entry of ART) {
    if (scene.textures.exists(entry.key)) continue;
    const canvas = entry.draw();
    const tex = scene.textures.addCanvas(entry.key, canvas);
    if (tex && entry.frame) {
      // Name frames 0,1,2... just like a loaded spritesheet would.
      for (let i = 0; i < entry.frame.count; i++) {
        tex.add(i, 0, i * entry.frame.w, 0, entry.frame.w, entry.frame.h);
      }
    }
  }
}
